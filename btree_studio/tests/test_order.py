"""Cross-check: the node order computed by the Studio (model.js) must match the
array generated by Scripts/btree_array_creator.py, for every tree of the examples.
Run:  python3 tests/test_order.py
"""
import json
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SCRIPTS = REPO / "Scripts"
EXAMPLES = [REPO / "btree_studio" / "examples" / "bc680z.xml",
            REPO / "examples" / "c99" / "tools" / "btree_robot" / "delivery.xml"] + \
           sorted((SCRIPTS / "tree-examples").glob("*.xml"))
MACRO = {
    "CONDITION": "condition", "ACTION": "action", "ACTION_SLEEP": "sleep",
    "RETRY_UNTIL_SUCCESS": "retry", "REPEAT": "repeat", "KEEP_RUNNING_UNTIL_FAILURE": "keep_running",
    "INVERTER": "inverter", "FORCE_SUCCESS": "force_success", "FORCE_FAIL": "force_failure",
}
LINE_RE = re.compile(r"\[(\d+)\] = BTREE_DEFINITION_CREATE_NODE_(?:REACTIVE_)?([A-Z_]+)\((.*)\),")


def python_order(xml, tree):
    with tempfile.TemporaryDirectory() as out:
        code = ("import sys\nfrom btree_array_creator import BTREE_ARRAY\n"
                "x=BTREE_ARRAY(); x.set_archive_data('a','b','1','','t')\n"
                "x.create_trees(archive=sys.argv[1], output=sys.argv[2], main_tree=sys.argv[3])\n")
        subprocess.run([sys.executable, "-c", code, str(xml), out, tree], cwd=SCRIPTS, check=True, capture_output=True)
        text = next(Path(out).rglob("*_array.c")).read_text()
    rows = []
    for m in LINE_RE.finditer(text):
        kind = MACRO[m.group(2)]
        args = [a.strip() for a in m.group(3).split(",")]
        target = lambda a: -1 if a == "BTREE_DEFINITION_TREE_UNRELATED" else int(a)
        rows.append((int(m.group(1)), kind, args[-1], target(args[0]), target(args[1])))
    rows.sort()
    return [(k, last, st, ft) for _, k, last, st, ft in rows]


def studio_order(xml, tree):
    out = subprocess.run(["node", str(HERE / "order_dump.js"), str(xml), tree], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def main():
    failures = 0
    total = 0
    for xml in EXAMPLES:
        for bt in ET.parse(xml).getroot().findall("BehaviorTree"):
            tree = bt.get("ID")
            py = python_order(xml, tree)
            js = studio_order(xml, tree)
            ok = len(py) == len(js)
            for (pk, plast, pst, pft), (jk, jval, jst, jft) in zip(py, js):
                if pk != jk or (pst, pft) != (jst, jft):
                    ok = False
                elif pk in ("action", "condition") and not plast.endswith("_" + jval):
                    ok = False
                elif pk == "sleep" and plast != jval:
                    ok = False
            total += 1
            print(f"{'OK  ' if ok else 'FAIL'} {xml.name}:{tree} ({len(js)} nós)")
            if not ok:
                failures += 1
                print("   python:", py)
                print("   studio:", js)
    print(f"\n{total - failures}/{total} árvores com ordem e saltos (st/ft) idênticos ao compilador.")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
